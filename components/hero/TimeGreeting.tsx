export type TimeOfDay = "morning" | "afternoon" | "evening";

function getClientTimeOfDay(): TimeOfDay {
  const hour = new Date().getHours();
  // Morning: 5:00 AM to 11:59 AM
  if (hour >= 5 && hour < 12) return "morning";
  // Afternoon: 12:00 PM to 4:59 PM
  if (hour >= 12 && hour < 17) return "afternoon";
  // Evening & Night: 5:00 PM onwards & early morning
  return "evening";
}

function getServerTimeOfDay(): TimeOfDay {
  return "morning";
}

function subscribe(onStoreChange: () => void) {
  // Check every 10 seconds for timely client transition
  const interval = setInterval(onStoreChange, 10000);
  return () => clearInterval(interval);
}

export default function TimeGreeting({
  className = "",
}: {
  className?: string;
}) {
  const greetingRef = useRef<HTMLDivElement>(null);
  const timeOfDay = useSyncExternalStore(
    subscribe,
    getClientTimeOfDay,
    getServerTimeOfDay
  );

  useEffect(() => {
    if (!greetingRef.current) return;

    const ctx = gsap.context(() => {
      // 1. Soft entry for cursive prefix "Good"
      gsap.fromTo(
        ".good-prefix",
        { opacity: 0, y: -10, rotate: -2 },
        { opacity: 1, y: 0, rotate: 0, duration: 0.5, ease: "power2.out" }
      );

      const letters = gsap.utils.toArray<SVGGElement>(".greeting-letter");
      if (letters.length === 0) return;

      // Let GSAP own the transform origin (set once, no CSS conflict)
      gsap.set(letters, { transformOrigin: "50% 100%" });

      // 2. Playful bouncy entrance for individual letters
      gsap.fromTo(
        letters,
        { y: 32, scaleY: 0.45, scaleX: 0.75, opacity: 0 },
        {
          y: 0,
          scaleY: 1,
          scaleX: 1,
          opacity: 1,
          duration: 0.65,
          ease: "back.out(2.2)",
          stagger: 0.045,
          delay: 0.08,
        }
      );

      // 3. Interactive hover animation on each letter
      const cleanups: (() => void)[] = [];

      letters.forEach((letter) => {
        const parent = letter.parentNode as SVGElement | null;
        if (!parent) return;

        // getBBox ignores the element's own transform, so this is safe
        // even while the entrance animation is running
        let bbox: DOMRect;
        try {
          bbox = letter.getBBox();
        } catch {
          return;
        }
        if (bbox.width === 0 || bbox.height === 0) return;

        // Stationary hit area: a SIBLING of the letter, not a child,
        // so it never moves when the letter animates
        const hitbox = document.createElementNS(
          "http://www.w3.org/2000/svg",
          "rect"
        );
        hitbox.setAttribute("x", String(bbox.x));
        hitbox.setAttribute("y", String(bbox.y - 14));
        hitbox.setAttribute("width", String(bbox.width));
        hitbox.setAttribute("height", String(bbox.height + 28));
        hitbox.setAttribute("fill", "transparent");
        hitbox.setAttribute("pointer-events", "all");
        hitbox.setAttribute("class", "letter-hitbox cursor-pointer");
        parent.insertBefore(hitbox, letter.nextSibling);

        const onEnter = () =>
          gsap.to(letter, {
            y: -8,
            scaleY: 1.09,
            scaleX: 0.95,
            duration: 0.2,
            ease: "back.out(2.4)",
            overwrite: true,
          });

        const onLeave = () =>
          gsap.to(letter, {
            y: 0,
            scaleY: 1,
            scaleX: 1,
            duration: 0.3,
            ease: "power2.out",
            overwrite: true,
          });

        hitbox.addEventListener("mouseenter", onEnter);
        hitbox.addEventListener("mouseleave", onLeave);

        cleanups.push(() => {
          hitbox.removeEventListener("mouseenter", onEnter);
          hitbox.removeEventListener("mouseleave", onLeave);
          hitbox.remove();
        });
      });

      return () => cleanups.forEach((fn) => fn());
    }, greetingRef);

    return () => ctx.revert();
  }, [timeOfDay]);

  return (
    <div
      ref={greetingRef}
      className={`flex flex-col items-start gap-1 select-none ${className}`}
      title={`Greeting: Good ${timeOfDay}`}
    >
      {/* Handwritten cursive prefix with Google's Italianno font */}
      <span
        className={`good-prefix ${italianno.className} text-5xl sm:text-6xl md:text-6xl lg:text-7xl xl:text-8xl 2xl:text-9xl font-normal text-red-600 leading-[0.95] tracking-tight`}
      >
        Good
      </span>

      {/* Dynamic Graphic SVG positioned directly below the prefix */}
      <div className="flex items-center max-w-full h-16 sm:h-20 md:h-24 lg:h-30 xl:h-36 2xl:h-42 mt-1 sm:mt-1.5 xl:mt-2.5 overflow-visible">
        {timeOfDay === "morning" && (
          <MorningSvg className="h-full w-auto max-w-full object-contain" />
        )}
        {timeOfDay === "afternoon" && (
          <AfternoonSvg className="h-full w-auto max-w-full object-contain" />
        )}
        {timeOfDay === "evening" && (
          <EveningSvg className="h-full w-auto max-w-full object-contain" />
        )}
      </div>
    </div>
  );
}